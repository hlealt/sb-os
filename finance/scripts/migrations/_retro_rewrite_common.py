"""Shared scaffolding for the retro-rewrite tool suite (p4-26).

The three retro-rewrite tools (`rename_tags.py`, `rename_canonical.py`,
`merge_categories.py`) are WRITE-class, use=retro-rewrite. They mutate
HISTORICAL classifications, but they NEVER edit historical ledger rows in
place — that is the append-only RED flag (shape.md Constraints; structured-
problem.md). The sanctioned mechanism (S5 p2-10, S4 p3-2, B2-IMP precedents):

  1. Append a row to the matching append-only corrections side-ledger
     (`tag-renames.csv` / `vendor-canonicals.csv` / `category-migrations.csv`).
     Rows are NEVER edited or deleted in place.
  2. Where a config file is the classifier's live source of truth (tags.json,
     suppliers.json, categories.json), update the config so future closes
     classify correctly. Config is regenerable agent-readable state, not a
     historical ledger.
  3. The derived output `transactions.csv` is regenerated by `categorize.py`,
     which joins the corrections + reads the updated config at read time.

These tools do NOT touch raw/historical ledger rows. They write only to the
corrections side-ledgers and the config files above.

This module provides the four non-negotiables shared by all three tools:

  * `--dry-run` is the DEFAULT. A real write requires an explicit `--apply`.
  * A fix-impact preview that enumerates EVERY affected location BEFORE any
    write (rows + configs + dashboard joins + tag namespaces + cross-tree deps).
  * A rollback path: every file a real run writes is first copied to a
    timestamped `.bak` beside it; `rollback()` restores from those backups.
  * An audit event per affected destination per run (via lib.audit, fail-soft).

Each tool builds an `ImpactReport` (a list of `Impact` rows), prints it, and —
only under `--apply` — performs its writes through `apply_writes()` which
handles backup-before-write and per-destination audit emission.
"""
