def load_json(path: Path) -> dict:
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def dump_json(path: Path, data: dict) -> None:
    """Write JSON preserving the project's 2-space indent + non-ASCII chars."""
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")


def append_correction_row(path: Path, fieldnames: list[str], row: dict) -> None:
    """Append one row to an append-only corrections CSV, writing the header if
    the file is new/empty. NEVER rewrites existing rows."""
    exists = path.exists() and path.stat().st_size > 0
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "a", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        if not exists:
            writer.writeheader()
        writer.writerow(row)


def iter_transactions_rows():
    """Yield (month, csv_path, row_dict) across every fechamento transactions.csv.

    Read-only. Used to ENUMERATE affected output rows for the fix-impact
    preview — never to mutate them (categorize.py regenerates them).
    """
    base = ledger_fechamento_dir()
    if not base.exists():
        return
    for month_dir in sorted(base.iterdir()):
        if not month_dir.is_dir():
            continue
        txfile = month_dir / "transactions.csv"
        if not txfile.exists():
            continue
        with open(txfile, "r", encoding="utf-8", newline="") as f:
            for row in csv.DictReader(f):
                yield month_dir.name, txfile, row


def now_iso() -> str:
    return _dt.datetime.now().replace(microsecond=0).isoformat()
