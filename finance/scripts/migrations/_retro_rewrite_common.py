# ---------------------------------------------------------------------------
# Impact model
# ---------------------------------------------------------------------------


@dataclass
class Impact:
    """One affected location in the fix-impact preview.

    `kind` groups the surface (config / correction-ledger / output-rows /
    dashboard-join / tag-namespace / cross-tree-dep). `writable` is True when
    THIS tool will write the location under --apply; False when the location is
    only *affected downstream* (e.g. transactions.csv is regenerated by
    categorize.py, not by this tool) or is a manual/cross-tree dependency the
    user must reconcile by hand.
    """

    kind: str
    location: str
    detail: str
    writable: bool = False
    # For writable file locations: a callable that performs the write. Receives
    # no args; returns None. Only invoked under --apply, after backup.
    writer: Callable[[], None] | None = None
    # Materiality for the audit event emitted when this location is written.
    materiality: str = "high"


@dataclass
class ImpactReport:
    tool: str
    operation: str  # human-readable, e.g. "rename tag 'boxe' -> 'esportes-luta'"
    impacts: list[Impact] = field(default_factory=list)
    # Blocking problems found during impact analysis (e.g. target tag missing).
    # A non-empty list means the operation is refused even under --apply.
    errors: list[str] = field(default_factory=list)
    # Non-blocking advisories surfaced to the user (e.g. a dormant consumer).
    warnings: list[str] = field(default_factory=list)

    def add(self, *a, **kw) -> None:
        self.impacts.append(Impact(*a, **kw))

    def writable_impacts(self) -> list[Impact]:
        return [i for i in self.impacts if i.writable and i.writer is not None]


# ---------------------------------------------------------------------------
# Preview rendering
# ---------------------------------------------------------------------------


_KIND_ORDER = [
    "correction-ledger",
    "config",
    "output-rows",
    "dashboard-join",
    "tag-namespace",
    "cross-tree-dep",
]


def print_impact_report(report: ImpactReport, *, applying: bool) -> None:
    mode = "APPLY (writing)" if applying else "DRY-RUN (no writes)"
    print("=" * 78)
    print(f"  {report.tool} — fix-impact preview  [{mode}]")
    print(f"  Operation: {report.operation}")
    print("=" * 78)

    if report.errors:
        print("\nBLOCKING ERRORS — operation refused:")
        for e in report.errors:
            print(f"  ✗ {e}")

    if report.warnings:
        print("\nWARNINGS:")
        for w in report.warnings:
            print(f"  ! {w}")

    by_kind: dict[str, list[Impact]] = {}
    for imp in report.impacts:
        by_kind.setdefault(imp.kind, []).append(imp)

    ordered_kinds = [k for k in _KIND_ORDER if k in by_kind]
    ordered_kinds += [k for k in by_kind if k not in _KIND_ORDER]

    print(f"\nAffected locations ({len(report.impacts)} total):")
    for kind in ordered_kinds:
        print(f"\n  [{kind}]")
        for imp in by_kind[kind]:
            marker = "WRITE " if imp.writable else "affected"
            print(f"    - ({marker}) {imp.location}")
            if imp.detail:
                print(f"          {imp.detail}")

    n_writable = sum(1 for i in report.impacts if i.writable)
    print("\n" + "-" * 78)
    print(
        f"  {n_writable} location(s) this tool will WRITE under --apply; "
        f"{len(report.impacts) - n_writable} affected downstream / "
        f"manually."
    )
    if not applying:
        print("  DRY-RUN: nothing was written. Re-run with --apply to execute.")
    print("-" * 78)


# ---------------------------------------------------------------------------
# Backup / rollback
# ---------------------------------------------------------------------------


def _backup_token() -> str:
    return _dt.datetime.now().strftime("%Y%m%dT%H%M%S")


def backup_path_for(target: Path, token: str) -> Path:
    """Backup sits beside the target: `<name>.bak.<token>`."""
    return target.with_name(f"{target.name}.bak.{token}")


def apply_writes(
    report: ImpactReport,
    *,
    source_function: str,
) -> dict:
    """Execute every writable impact under a single backup token.

    For each writable location:
      1. If the destination file already exists, copy it to a timestamped
         `.bak.<token>` first (the rollback anchor). New files get no backup
         row but are recorded so rollback can delete them.
      2. Run the writer.
      3. Emit one audit event (best-effort, never raises).

    Returns a manifest dict (used by rollback + tests):
      {token, backups: [{target, backup, existed_before}], ...}
    """
    token = _backup_token()
    backups: list[dict] = []

    for imp in report.writable_impacts():
        target = Path(imp.location)
        existed_before = target.exists()
        backup = None
        if existed_before:
            backup = backup_path_for(target, token)
            shutil.copy2(target, backup)
        backups.append(
            {
                "target": str(target),
                "backup": str(backup) if backup else None,
                "existed_before": existed_before,
            }
        )

        # Perform the write.
        assert imp.writer is not None
        imp.writer()

        # One audit event per affected destination per run (fail-soft).
        if audit is not None:
            try:
                audit.emit(
                    "config_write",
                    source_function=source_function,
                    destination=target,
                    action="append" if imp.kind == "correction-ledger" else "overwrite",
                    materiality=imp.materiality,
                    summary={
                        "retro_rewrite": report.tool,
                        "operation": report.operation,
                        "kind": imp.kind,
                    },
                )
            except Exception:  # pragma: no cover - audit is best-effort
                pass

    manifest = {
        "tool": report.tool,
        "operation": report.operation,
        "token": token,
        "backups": backups,
    }
    return manifest


def rollback(manifest: dict) -> list[str]:
    """Restore prior state from an apply_writes() manifest.

    For each recorded target: restore its `.bak.<token>` (byte-for-byte) if one
    was made; if the target did NOT exist before the run (no backup), delete the
    file the run created. Returns a list of human-readable actions taken.
    """
    actions: list[str] = []
    # Reverse order so newer writes are undone first (defensive; order-agnostic
    # for independent files but correct if any future target nests).
    for entry in reversed(manifest.get("backups", [])):
        target = Path(entry["target"])
        backup = entry.get("backup")
        if entry.get("existed_before") and backup:
            shutil.copy2(backup, target)
            actions.append(f"restored {target.name} from {Path(backup).name}")
        elif not entry.get("existed_before"):
            if target.exists():
                target.unlink()
                actions.append(f"deleted {target.name} (did not exist before run)")
    return actions


def write_manifest(manifest: dict, *, label: str) -> Path:
    """Persist the apply manifest beside the corrections dir under
    `corrections/.rollback/<label>-<token>.json` so a later invocation (or the
    user) can roll the change back. Returns the manifest path.
    """
    rb_dir = corrections_dir() / ".rollback"
    rb_dir.mkdir(parents=True, exist_ok=True)
    path = rb_dir / f"{label}-{manifest['token']}.json"
    with open(path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)
    return path


